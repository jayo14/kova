import type { Metadata } from "next";
import { requireOrg } from "@/lib/auth/guards";
import { getAccessToken } from "@/lib/auth/server";
import { AppShell } from "@/components/shell/app-shell";
import { getExecutions } from "@/lib/api/executions";
import { getRun } from "@/lib/api/runs";
import { ExecutionList } from "@/components/executions";
import { RunOverview } from "@/components/executions/run-overview";

export const metadata: Metadata = {
  title: "Proof & Runs — Kova",
  description: "Visual verification runs and proof generated by Kova.",
};

interface ExecutionsPageProps {
  searchParams: Promise<{ runId?: string }>;
}

export default async function ExecutionsPage({ searchParams }: ExecutionsPageProps) {
  const { session, user, organization } = await requireOrg("/executions");
  const token = (await getAccessToken()) ?? session.access_token;

  const resolvedParams = await searchParams;
  const runId = resolvedParams?.runId;

  if (runId) {
    const initialRun = await getRun(runId, token).catch(() => null);
    return (
      <AppShell user={user} organizationName={organization.name}>
        <div className="mx-auto w-full max-w-[1600px] animate-in px-4 py-6 fade-in duration-300 sm:px-6">
          <RunOverview runId={runId} initialRun={initialRun ?? undefined} />
        </div>
      </AppShell>
    );
  }

  const executions = await getExecutions(undefined, token).catch(() => []);

  return (
    <AppShell user={user} organizationName={organization.name}>
      <div className="mx-auto w-full max-w-5xl animate-in px-6 py-10 fade-in duration-300 md:py-14">
        <div className="mb-8">
          <h1 className="text-display sm:text-[2.25rem] font-bold text-foreground mb-1.5 tracking-tight">
            Runs &amp; Visual Proof
          </h1>
          <p className="text-body-sm text-muted-foreground leading-relaxed">
            Visual verification runs, regression evidence, and step replays.
          </p>
        </div>

        <ExecutionList executions={executions} />
      </div>
    </AppShell>
  );
}
