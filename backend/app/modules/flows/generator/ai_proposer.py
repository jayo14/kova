import logging
import uuid
from typing import Any

from sqlalchemy.ext.asyncio import AsyncSession

from app.engine.ai.provider import get_ai_provider
from app.engine.ai.reasoner import AgentReasoner
from app.engine.ai.settings import ai_settings
from app.modules.flows.generator.representations import (
    to_gherkin_representation,
    to_json_representation,
)
from app.modules.flows.generator.schemas import (
    ExecutionStep,
    GeneratedFlow,
)
from app.modules.flows.schemas import FlowStateContract, StateAssertion
from app.modules.product_graph.repository import ProductGraphRepository
from app.modules.product_graph.schemas import AIProposal

logger = logging.getLogger(__name__)


class AIFlowProposer:
    """Proposes flows using AI for goals the deterministic generator cannot resolve."""

    def __init__(self, db: AsyncSession):
        self.db = db
        self.repo = ProductGraphRepository(db)

    async def propose(
        self,
        project_id: uuid.UUID,
        unresolved_goals: list[str],
    ) -> tuple[list[GeneratedFlow], list[AIProposal]]:
        """Call AI Reasoner to propose executable flows for unresolved goals."""
        if not ai_settings.ai_enabled:
            return [], []

        provider = get_ai_provider()
        reasoner = AgentReasoner(provider=provider)

        # Collect product graph context summary
        pages = await self.repo.list_pages_by_project(project_id)
        actions = await self.repo.list_actions_by_project(project_id)
        capabilities = await self.repo.list_capabilities_by_project(project_id)

        graph_summary = {
            "pages": [{"url": p.url_pattern, "title": p.title} for p in pages[:15]],
            "capabilities": [c.name for c in capabilities[:20]],
            "sample_actions": [{"name": a.name, "selector": a.selector} for a in actions[:25]],
        }

        proposed_flows: list[GeneratedFlow] = []
        ai_proposals: list[AIProposal] = []

        for goal_name in unresolved_goals:
            try:
                proposals = await reasoner.propose_flows(goal_name, graph_summary)
                for prop in proposals:
                    raw_steps = prop.get("steps") or []
                    steps: list[ExecutionStep] = []
                    for s in raw_steps:
                        steps.append(
                            ExecutionStep(
                                action=s.get("action", "navigate"),
                                target=s.get("target"),
                                value=s.get("value"),
                                description=s.get("description"),
                            )
                        )

                    confidence = min(float(prop.get("confidence", 0.8)), 0.9)
                    flow_name = prop.get("name") or f"Proposed Flow for {goal_name}"

                    state_contract = FlowStateContract(
                        requires=[],
                        produces=[StateAssertion(key=f"goal_{goal_name}", value=True, predicate="eq")],
                        mutates=[f"goal_{goal_name}"],
                    )

                    json_repr = to_json_representation(
                        name=flow_name,
                        steps=steps,
                        state_contract=state_contract,
                        source="ai_proposal",
                        confidence=confidence,
                    )
                    gherkin = to_gherkin_representation(flow_name, steps)

                    flow = GeneratedFlow(
                        name=flow_name,
                        state_contract=state_contract,
                        internal=steps,
                        json_repr=json_repr,
                        gherkin=gherkin,
                        source="ai_proposal",
                        confidence=confidence,
                    )
                    proposed_flows.append(flow)

                    ai_proposals.append(
                        AIProposal(
                            stage="flow_generation",
                            input_summary=f"Unresolved goal: {goal_name}",
                            output_summary=f"Proposed flow '{flow_name}' with {len(steps)} steps",
                            accepted=True,
                            reasoning=prop.get("reasoning", "Generated by AI Reasoner"),
                            confidence=confidence,
                        )
                    )
            except Exception as e:
                logger.warning("AIFlowProposer failed for goal '%s': %s", goal_name, e)

        return proposed_flows, ai_proposals
